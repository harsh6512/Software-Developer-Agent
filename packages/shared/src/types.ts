import { Annotation, messagesStateReducer } from "@langchain/langgraph";
import { BaseMessage } from "@langchain/core/messages";

// Target Git repository
export interface TargetRepository {
    owner: string;
    repo: string;
    branch?: string;
    baseCommit?: string;
}

// Single step in an implementation plan
export interface PlanItem {
    index: number;
    plan: string;
    completed: boolean;
    summary?: string;
}

// Revision tracking for the plan (human edits vs agent edits)
export interface PlanRevision {
    revisionIndex: number;
    plans: PlanItem[];
    createdAt: number;
    createdBy: "agent" | "user";
}

// User-level task tracking
export interface Task {
    id: string;
    taskIndex: number;
    request: string;
    title: string;
    createdAt: number;
    completed: boolean;
    completedAt?: number;
    summary?: string;
    planRevisions: PlanRevision[];
    activeRevisionIndex: number;
    pullRequestNumber?: number;
}

// The active task plan
export interface TaskPlan {
    tasks: Task[];
    activeTaskIndex: number;
}

// Testing stage status
export type TestingStatus =
    | "not_started"
    | "required"
    | "in_progress"
    | "completed"
    | "failed"
    | "skipped";

// Optional custom rules / conventions
export interface CustomRules {
    generalRules?: string;
    repositoryStructure?: string;
    dependenciesAndInstallation?: string;
    testingInstructions?: string;
    pullRequestFormatting?: string;
}

// -------------------------------------------------------------------------
// LangGraph State Definition
// -------------------------------------------------------------------------
export const GraphAnnotation = Annotation.Root({
    // User-facing messages displayed in the UI chat
    messages: Annotation<BaseMessage[]>({
        reducer: messagesStateReducer,
        default: () => [],
    }),

    // Internal agent working messages (tool calls, thinking, trimmed context)
    internalMessages: Annotation<BaseMessage[]>({
        reducer: messagesStateReducer,
        default: () => [],
    }),

    // Active implementation plan
    taskPlan: Annotation<TaskPlan | null>({
        reducer: (_prev, next) => next,
        default: () => null,
    }),

    // Scratchpad notes gathered during planning
    contextGatheringNotes: Annotation<string>({
        reducer: (_prev, next) => next,
        default: () => "",
    }),

    // Active Daytona Sandbox Container ID
    sandboxSessionId: Annotation<string>({
        reducer: (_prev, next) => next,
        default: () => "",
    }),

    // Target GitHub repository
    targetRepository: Annotation<TargetRepository>({
        reducer: (_prev, next) => next,
    }),

    // Working branch name (e.g. `agentic/fix-issue-12`)
    branchName: Annotation<string>({
        reducer: (_prev, next) => next,
        default: () => "",
    }),

    // Formatted directory tree string generated by tree.ts
    codebaseTree: Annotation<string>({
        reducer: (_prev, next) => next,
        default: () => "",
    }),

    // Status of the testing subgraph
    testingStatus: Annotation<TestingStatus>({
        reducer: (_prev, next) => next,
        default: () => "not_started",
    }),

    // Number of review cycles performed by Reviewer subgraph
    reviewsCount: Annotation<number>({
        reducer: (_prev, next) => next,
        default: () => 0,
    }),

    // Custom rules or style guides
    customRules: Annotation<CustomRules | undefined>({
        reducer: (_prev, next) => next,
    }),
});

// TypeScript helpers derived from Annotation
export type GraphState = typeof GraphAnnotation.State;
export type GraphUpdate = typeof GraphAnnotation.Update;
